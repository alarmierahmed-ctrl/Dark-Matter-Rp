-- إنشاء الطلب من قاعدة البيانات نفسها حتى لا يقدر العميل يغير السعر من المتصفح.
drop policy if exists "buyer creates own order" on public.orders;

create or replace function public.create_store_order(
  p_product_id bigint,
  p_discount_code text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.store_products%rowtype;
  d public.discount_codes%rowtype;
  settings public.store_settings%rowtype;
  discount_value_calc numeric(10,2) := 0;
  final_price numeric(10,2);
  result_order public.orders%rowtype;
  code_clean text := nullif(upper(trim(coalesce(p_discount_code,''))), '');
  buyer_email_value text := lower(coalesce(auth.jwt()->>'email',''));
  buyer_name_value text := coalesce(
    auth.jwt()->'user_metadata'->>'full_name',
    auth.jwt()->'user_metadata'->>'name',
    auth.jwt()->'user_metadata'->>'user_name',
    buyer_email_value
  );
begin
  if auth.uid() is null then
    raise exception 'يجب تسجيل الدخول أولاً';
  end if;

  select * into settings from public.store_settings where id = 1;
  if settings.id is not null and not settings.store_enabled then
    raise exception 'المتجر مغلق حالياً';
  end if;

  select * into p
  from public.store_products
  where id = p_product_id and active = true;

  if p.id is null then
    raise exception 'المنتج غير موجود أو غير متاح';
  end if;

  final_price := p.price;

  if code_clean is not null then
    select * into d
    from public.discount_codes
    where upper(code) = code_clean
    limit 1;

    if d.id is null then raise exception 'كود الخصم غير صحيح'; end if;
    if not d.active then raise exception 'كود الخصم غير مفعل'; end if;
    if d.starts_at is not null and now() < d.starts_at then raise exception 'كود الخصم لم يبدأ بعد'; end if;
    if d.expires_at is not null and now() > d.expires_at then raise exception 'انتهت صلاحية كود الخصم'; end if;
    if d.max_uses is not null and d.used_count >= d.max_uses then raise exception 'تم استهلاك كود الخصم'; end if;
    if p.price < d.min_order then raise exception 'سعر المنتج أقل من الحد الأدنى للكود'; end if;

    if d.discount_type = 'percent' then
      discount_value_calc := round(p.price * least(d.discount_value,100) / 100.0, 2);
    else
      discount_value_calc := least(d.discount_value, p.price);
    end if;

    final_price := greatest(0, round(p.price - discount_value_calc, 2));

    update public.discount_codes
    set used_count = used_count + 1, updated_at = now()
    where id = d.id;
  end if;

  insert into public.orders(
    buyer_id,buyer_email,buyer_name,product_id,product_name,
    original_price,discount_code,discount_amount,price,amount_halalas,
    currency,status,payment_status,updated_at
  )
  values(
    auth.uid(),buyer_email_value,buyer_name_value,p.id,p.name,
    p.price,code_clean,discount_value_calc,final_price,round(final_price*100)::integer,
    'SAR','بانتظار الدفع','pending',now()
  )
  returning * into result_order;

  return result_order;
end;
$$;

revoke all on function public.create_store_order(bigint,text) from public;
grant execute on function public.create_store_order(bigint,text) to authenticated;

notify pgrst, 'reload schema';
