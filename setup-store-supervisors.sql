create extension if not exists pgcrypto;

-- إعدادات المتجر
create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  store_title text not null default 'المتجر',
  store_subtitle text not null default 'المنتجات المتوفرة: طاولات التصنيع — انتقال الهليكوبترات — منتج خاص',
  announcement text not null default '',
  store_enabled boolean not null default true,
  updated_at timestamptz not null default now()
);

insert into public.store_settings(id)
values (1)
on conflict (id) do nothing;

-- المنتجات والسيارات
create table if not exists public.store_products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'car'
    check (category in ('car','crafting','helicopter','other')),
  description text not null default '',
  price numeric(10,2) not null default 22.99 check (price >= 0),
  image_url text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- أكواد الخصم
create table if not exists public.discount_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  discount_type text not null check (discount_type in ('percent','fixed')),
  discount_value numeric(10,2) not null check (discount_value >= 0),
  min_order numeric(10,2) not null default 0 check (min_order >= 0),
  max_uses integer null check (max_uses is null or max_uses >= 1),
  used_count integer not null default 0 check (used_count >= 0),
  starts_at timestamptz null,
  expires_at timestamptz null,
  active boolean not null default true,
  created_by text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists discount_codes_code_lower_uidx
on public.discount_codes (lower(code));

