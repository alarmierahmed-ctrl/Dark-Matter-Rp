-- صلاحية موحدة للمالك أو المشرف
create or replace function public.is_store_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_site_owner() or public.is_site_supervisor();
$$;

grant execute on function public.is_store_staff() to authenticated;

